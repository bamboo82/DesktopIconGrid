using DesktopIconGrid.Core.Launching;

namespace DesktopIconGrid.Core.Imports;

/// <summary>An installed app as the Start menu lists it (<c>shell:AppsFolder</c>), and the location the bar stores for it.</summary>
/// <param name="Name">The name the Start menu shows.</param>
/// <param name="Location">A program path, a link, or <c>shell:AppsFolder\…</c> for an app only the shell can start.</param>
/// <param name="IsStoreApp">A packaged (Store) app, started through its app user model id.</param>
public sealed record InstalledApp(string Name, string Location, bool IsStoreApp);

/// <summary>
/// Turns an entry of <c>shell:AppsFolder</c> into a location. The entries' parsing names come in these shapes: a Store
/// app's id (<c>Microsoft.WindowsCalculator_8wekyb3d8bbwe!App</c>), a path below a known folder
/// (<c>{6D809377-6AF0-444B-8957-A3773F02200E}\Tool\tool.exe</c>), a plain path (<c>C:\Tools\WinRAR\WinRAR.exe</c>), a
/// link of any scheme (<c>https://…</c>, <c>steam://…</c>), or an id a desktop program registered for its Start menu
/// shortcut (<c>Chrome</c>, <c>Microsoft.AutoGenerated.{…}</c>). A path becomes the real path, and so does a
/// registered id whose shortcut starts an <c>.exe</c> with nothing to add (see <see cref="ProgramOf"/>), so the running
/// badge, switching and the missing check work as for any program. The rest are started through the shell.
/// </summary>
public static partial class AppsFolderEntry
{
    /// <summary>
    /// The location for an entry. <paramref name="knownFolderPath"/> resolves a known folder's id to its path;
    /// <paramref name="linkTarget"/> and <paramref name="linkArguments"/> are what a registered id's shortcut starts, when
    /// the shell says (see <see cref="NeedsLinkTarget"/>).
    /// </summary>
    public static InstalledApp? ToApp(string? name, string? parsingName, Func<Guid, string?> knownFolderPath, string? linkTarget = null, string? linkArguments = null)
    {
        ArgumentNullException.ThrowIfNull(knownFolderPath);
        if (string.IsNullOrWhiteSpace(name) || string.IsNullOrWhiteSpace(parsingName))
        {
            return null;
        }

        var parsing = parsingName.Trim();
        var display = name.Trim();
        if (KnownFolderPath(parsing) is { } known)
        {
            return knownFolderPath(known.FolderId) is { Length: > 0 } folder && known.Remainder.Length > 0
                ? new InstalledApp(display, Path.Combine(folder, known.Remainder), IsStoreApp: false)
                : new InstalledApp(display, PackagedApps.AppsFolderPrefix + parsing, IsStoreApp: false);
        }

        if (IsWindowsPath(parsing) || LaunchPlanner.IsUri(parsing))
        {
            return new InstalledApp(display, parsing, IsStoreApp: false);
        }

        if (IsStoreAppId(parsing))
        {
            return new InstalledApp(display, PackagedApps.AppsFolderPrefix + parsing, IsStoreApp: true);
        }

        return ProgramOf(linkTarget, linkArguments) is { } program
            ? new InstalledApp(display, program, IsStoreApp: false)
            : new InstalledApp(display, PackagedApps.AppsFolderPrefix + parsing, IsStoreApp: false);
    }

    /// <summary>Whether <paramref name="parsingName"/> is an id a desktop program registered, whose shortcut's target is worth reading.</summary>
    public static bool NeedsLinkTarget(string? parsingName)
    {
        var parsing = parsingName?.Trim() ?? string.Empty;
        return parsing.Length > 0
            && KnownFolderPath(parsing) is null
            && !IsWindowsPath(parsing)
            && !LaunchPlanner.IsUri(parsing)
            && !IsStoreAppId(parsing)
            && !parsing.StartsWith("::", StringComparison.Ordinal);
    }

    /// <summary>
    /// The program a registered id stands for, when starting it directly loses nothing: a full path to an
    /// <c>.exe</c> started without arguments, or with only the note Chrome and Edge get of where they were started
    /// from (<c>--source-shortcut-location=start-menu</c>). <see langword="null"/> otherwise: the id keeps its arguments.
    /// </summary>
    public static string? ProgramOf(string? target, string? arguments)
    {
        var path = target?.Trim().Trim('"') ?? string.Empty;
        if (!IsWindowsPath(path) || !path.EndsWith(".exe", StringComparison.OrdinalIgnoreCase))
        {
            return null;
        }

        var rest = arguments?.Trim() ?? string.Empty;
        return rest.Length == 0 || SourceNote().IsMatch(rest) ? path : null;
    }

    /// <summary>A path on a drive letter or a network share, written the Windows way whatever system this runs on.</summary>
    private static bool IsWindowsPath(string value) =>
        (value.Length >= 3 && char.IsAsciiLetter(value[0]) && value[1] == ':' && value[2] is '\\' or '/')
        || value.StartsWith(@"\\", StringComparison.Ordinal);

    private static bool IsStoreAppId(string parsing) => parsing.Contains('!', StringComparison.Ordinal);

    /// <summary><c>{known folder id}\rest</c> as the id and the rest, or <see langword="null"/>.</summary>
    private static (Guid FolderId, string Remainder)? KnownFolderPath(string parsing) =>
        parsing.StartsWith('{') && parsing.IndexOf('}') is var close and > 1 && Guid.TryParse(parsing[1..close], out var folderId)
            ? (folderId, parsing[(close + 1)..].TrimStart('\\'))
            : null;

    [System.Text.RegularExpressions.GeneratedRegex("^\"?--source-shortcut-location=[^\\s\"]*\"?$", System.Text.RegularExpressions.RegexOptions.IgnoreCase | System.Text.RegularExpressions.RegexOptions.CultureInvariant)]
    private static partial System.Text.RegularExpressions.Regex SourceNote();
}
