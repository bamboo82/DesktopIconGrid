using DesktopIconGrid.Core.Imports;
using DesktopIconGrid.Core.Launching;

namespace DesktopIconGrid.Core.Tests;

/// <summary>Add app…: what the bar stores for each kind of Start menu entry.</summary>
public class AppsFolderEntryTests
{
    private static readonly Guid ProgramFilesX86 = new("7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E");

    private static string? Known(Guid id) => id == ProgramFilesX86 ? @"C:\Program Files (x86)" : null;

    [Fact]
    public void A_path_below_a_known_folder_becomes_the_real_path()
    {
        Assert.Equal(
            new InstalledApp("WinSCP", Path.Combine(@"C:\Program Files (x86)", @"WinSCP\WinSCP.exe"), IsStoreApp: false),
            AppsFolderEntry.ToApp("WinSCP", "{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}\\WinSCP\\WinSCP.exe", Known));
    }

    [Fact]
    public void Store_apps_and_registered_ids_are_started_through_the_shell()
    {
        Assert.Equal(
            new InstalledApp("Calculator", @"shell:AppsFolder\Microsoft.WindowsCalculator_8wekyb3d8bbwe!App", IsStoreApp: true),
            AppsFolderEntry.ToApp(" Calculator ", "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App", Known));
        Assert.Equal(
            new InstalledApp("File Explorer", @"shell:AppsFolder\Microsoft.Windows.Explorer", IsStoreApp: false),
            AppsFolderEntry.ToApp("File Explorer", "Microsoft.Windows.Explorer", Known));
        Assert.Equal( // a known folder this PC cannot resolve: left to the shell
            new InstalledApp("Tool", @"shell:AppsFolder\{11111111-2222-3333-4444-555555555555}\Tool\tool.exe", IsStoreApp: false),
            AppsFolderEntry.ToApp("Tool", @"{11111111-2222-3333-4444-555555555555}\Tool\tool.exe", Known));
    }

    [Fact]
    public void A_plain_path_is_stored_as_it_is_not_through_the_shell()
    {
        // The review: 42 entries on one PC, WinRAR among them, became shell:AppsFolder\C:\…
        Assert.Equal(new InstalledApp("WinRAR", @"C:\+\WinRAR\WinRAR.exe", IsStoreApp: false), AppsFolderEntry.ToApp("WinRAR", @"C:\+\WinRAR\WinRAR.exe", Known));
        Assert.Equal(new InstalledApp("Tool", @"\\nas\apps\tool.exe", IsStoreApp: false), AppsFolderEntry.ToApp("Tool", @"\\nas\apps\tool.exe", Known));
        Assert.False(AppsFolderEntry.NeedsLinkTarget(@"C:\+\WinRAR\WinRAR.exe"));
    }

    [Fact]
    public void A_link_of_any_scheme_stays_a_link()
    {
        Assert.Equal(new InstalledApp("Dota 2", "steam://rungameid/570", IsStoreApp: false), AppsFolderEntry.ToApp("Dota 2", "steam://rungameid/570", Known));
        Assert.False(AppsFolderEntry.NeedsLinkTarget("steam://rungameid/570"));
    }

    [Fact]
    public void A_shell_object_is_left_to_the_shell()
    {
        const string clsid = "::{26EE0668-A00A-44D7-9371-BEB064C98683}";

        Assert.Equal(new InstalledApp("Control Panel", PackagedApps.AppsFolderPrefix + clsid, IsStoreApp: false), AppsFolderEntry.ToApp("Control Panel", clsid, Known));
        Assert.False(AppsFolderEntry.NeedsLinkTarget(clsid));
    }

    [Fact]
    public void A_registered_id_becomes_its_program_when_it_starts_one_with_nothing_to_add()
    {
        const string firefox = "E7CF176E110C211B";
        const string autoGenerated = "Microsoft.AutoGenerated.{923DD477-5846-686B-A659-0FCCD73851A8}";
        Assert.True(AppsFolderEntry.NeedsLinkTarget(firefox));
        Assert.True(AppsFolderEntry.NeedsLinkTarget(autoGenerated));
        Assert.False(AppsFolderEntry.NeedsLinkTarget("Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"));

        Assert.Equal(
            new InstalledApp("Firefox", @"C:\Program Files\Mozilla Firefox\firefox.exe", IsStoreApp: false),
            AppsFolderEntry.ToApp("Firefox", firefox, Known, @"C:\Program Files\Mozilla Firefox\firefox.exe", string.Empty));
        Assert.Equal( // only where it was started from: the program itself is better
            new InstalledApp("Google Chrome", @"C:\Program Files\Google\Chrome\Application\chrome.exe", IsStoreApp: false),
            AppsFolderEntry.ToApp("Google Chrome", "Chrome", Known, @"C:\Program Files\Google\Chrome\Application\chrome.exe", "--source-shortcut-location=start-menu"));
        Assert.Equal( // real arguments: the id keeps them
            new InstalledApp("Tool (safe mode)", PackagedApps.AppsFolderPrefix + autoGenerated, IsStoreApp: false),
            AppsFolderEntry.ToApp("Tool (safe mode)", autoGenerated, Known, @"C:\Tools\tool.exe", "--safe-mode"));
        Assert.Equal( // not a program
            new InstalledApp("Readme", PackagedApps.AppsFolderPrefix + autoGenerated, IsStoreApp: false),
            AppsFolderEntry.ToApp("Readme", autoGenerated, Known, @"C:\Tools\readme.txt", null));
        Assert.Equal( // the shell did not say
            new InstalledApp("Word", @"shell:AppsFolder\Microsoft.Office.WINWORD.EXE.15", IsStoreApp: false),
            AppsFolderEntry.ToApp("Word", "Microsoft.Office.WINWORD.EXE.15", Known));
    }

    [Fact]
    public void Links_stay_links_and_nameless_entries_are_skipped()
    {
        Assert.Equal(new InstalledApp("Help", "https://example.com/help", IsStoreApp: false), AppsFolderEntry.ToApp("Help", "https://example.com/help", Known));
        Assert.Null(AppsFolderEntry.ToApp("", "x!App", Known));
        Assert.Null(AppsFolderEntry.ToApp("Name", null, Known));
    }
}
